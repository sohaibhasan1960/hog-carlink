    fun ayahCount(surah: Int): Int = AYAHS[surah - 1]

    private fun code(surah: Int, ayah: Int) = surah * 1000 + ayah

    /** Аят после данного (сура * 1000 + аят); после 114:6 - страж 115001. */
    private fun next(c: Int): Int {
        val s = c / 1000
        val a = c % 1000
        return if (a < AYAHS[s - 1]) c + 1 else code(s + 1, 1)
    }

    /** Аяты страницы по порядку: сура * 1000 + аят. */
    fun ayahs(page: Int): List<Int> {
        val p = page.coerceIn(1, PAGES)
        val out = ArrayList<Int>()
        var c = START[p - 1]
        val end = START[p]
        while (c != end) {
            out += c
            c = next(c)
        }
        return out
    }

    /** Страница, на которой стоит аят. */
    fun pageOf(surah: Int, ayah: Int): Int {
        val c = code(surah, ayah)
        var lo = 0
        var hi = PAGES - 1
        while (lo < hi) {
            val mid = (lo + hi + 1) / 2
            if (START[mid] <= c) lo = mid else hi = mid - 1
        }
        return lo + 1
    }

    /** Джуз (1..30) по первому аяту страницы. */
    fun juzOf(page: Int): Int {
        val c = START[page.coerceIn(1, PAGES) - 1]
        return (1..30).last { JUZ[it - 1] <= c }
    }

    /** Суры на странице (по порядку, без повторов). */
    fun surahs(page: Int): List<Int> = ayahs(page).map { it / 1000 }.distinct()

    /**
     * Файлы everyayah для страницы: SSSAAA.mp3 по порядку. Перед первым аятом суры (кроме аль-Фатихи, где басмала -
     * сам аят 1, и ат-Таубы без басмалы) - басмала 001001, как в мусхафе.
     */
    fun files(page: Int): List<String> {
        val out = ArrayList<String>()
        for (c in ayahs(page)) {
            val s = c / 1000
            val a = c % 1000
            if (a == 1 && s != 1 && s != 9) out += BASMALA
            out += "%03d%03d.mp3".format(s, a)
        }
        return out
    }

